func TestExecutionIntent_RouteOperationBoundary(t *testing.T) {
	command := "route add default gw 192.0.2.1"
	if reason := matchesWritePatterns(command, command); reason != "" {
		t.Fatalf("route operation matched an unrelated write pattern: %s", reason)
	}
	if isReadOnlyByConstruction(command) {
		t.Fatal("route add must fail argument validation")
	}
	if reason := matchesWritePatterns("dd if=/dev/zero of=/tmp/x", "dd if=/dev/zero of=/tmp/x"); reason != "disk write" {
		t.Fatalf("dd classification = %q, want disk write", reason)
	}
}
