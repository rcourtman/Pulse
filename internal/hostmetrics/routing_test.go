// The route table of a Proxmox node on a flat LAN, as the kernel prints it:
// the default route through the bridge, and the bridge's own subnet.
const procNetRouteBridge = "Iface\tDestination\tGateway \tFlags\tRefCnt\tUse\tMetric\tMask\t\tMTU\tWindow\tIRTT\n" +
	"vmbr0\t00000000\t0100A8C0\t0003\t0\t0\t0\t00000000\t0\t0\t0\n" +
	"vmbr0\t0000A8C0\t00000000\t0001\t0\t0\t0\t00FFFFFF\t0\t0\t0\n"

func TestParseProcNetRouteReadsTheDefaultGateway(t *testing.T) {
	got := parseProcNetRoute(procNetRouteBridge)
	want := []agentshost.NetworkGateway{{Address: "192.168.0.1", Interface: "vmbr0"}}
	if !reflect.DeepEqual(got, want) {
		t.Fatalf("gateways = %+v, want %+v", got, want)
	}
}

func TestParseProcNetRouteOrdersByMetricAndSkipsWhatNamesNoNextHop(t *testing.T) {
	table := "Iface\tDestination\tGateway \tFlags\tRefCnt\tUse\tMetric\tMask\t\tMTU\tWindow\tIRTT\n" +
		// Wi-Fi backup route, higher metric.
		"wlan0\t00000000\t01010A0A\t0003\t0\t0\t600\t00000000\t0\t0\t0\n" +
		// Wired route, lower metric, listed second.
		"eth0\t00000000\t0100A8C0\t0003\t0\t0\t100\t00000000\t0\t0\t0\n" +
		// The same route again must not be listed twice.
		"eth0\t00000000\t0100A8C0\t0003\t0\t0\t100\t00000000\t0\t0\t0\n" +
		// A default route with no gateway: a point-to-point link.
		"wg0\t00000000\t00000000\t0001\t0\t0\t0\t00000000\t0\t0\t0\n" +
		// A default route that is down.
		"eth1\t00000000\t0101A8C0\t0002\t0\t0\t50\t00000000\t0\t0\t0\n" +
		// A host route through a gateway is not a default route.
		"eth0\t08080808\t0100A8C0\t0007\t0\t0\t0\tFFFFFFFF\t0\t0\t0\n" +
		// Garbage.
		"eth2\t00000000\tZZZZZZZZ\t0003\t0\t0\t0\t00000000\t0\t0\t0\n" +
		"short line\n"
	got := parseProcNetRoute(table)
	want := []agentshost.NetworkGateway{
		{Address: "192.168.0.1", Interface: "eth0"},
		{Address: "10.10.1.1", Interface: "wlan0"},
	}
	if !reflect.DeepEqual(got, want) {
		t.Fatalf("gateways = %+v, want %+v", got, want)
	}
	if parseProcNetRoute("") != nil {
		t.Fatal("an empty table must report no gateways")
	}
}

func TestParseProcNetRouteBoundsTheList(t *testing.T) {
	var table strings.Builder
	table.WriteString("Iface\tDestination\tGateway \tFlags\tRefCnt\tUse\tMetric\tMask\n")
	for i := 0; i < maxDefaultGateways+4; i++ {
		// 10.0.0.1 through a different interface each time.
		table.WriteString(fmt.Sprintf("eth%d\t00000000\t0100000A\t0003\t0\t0\t0\t00000000\n", i))
	}
	if got := parseProcNetRoute(table.String()); len(got) != maxDefaultGateways {
		t.Fatalf("got %d gateways, want the bound of %d", len(got), maxDefaultGateways)
	}
}

func TestParseResolvConfReadsNameserversInOrder(t *testing.T) {
	conf := "# Generated by resolvconf\n" +
		"search lan example.test\n" +
		"nameserver 192.168.0.53\n" +
		"nameserver 192.168.0.53   # listed twice\n" +
		"nameserver fd7a:115c:a1e0::53\n" +
		"nameserver   1.1.1.1 ; trailing comment\n" +
		"nameserver not-an-address\n" +
		"nameserver 0.0.0.0\n" +
		"#nameserver 9.9.9.9\n" +
		"options edns0\n"
	got := parseResolvConf(conf)
	want := []string{"192.168.0.53", "fd7a:115c:a1e0::53", "1.1.1.1"}
	if !reflect.DeepEqual(got, want) {
		t.Fatalf("servers = %v, want %v", got, want)
	}

	var many strings.Builder
	for i := 1; i <= maxDNSServers+3; i++ {
		many.WriteString(fmt.Sprintf("nameserver 10.0.0.%d\n", i))
	}
	if got := parseResolvConf(many.String()); len(got) != maxDNSServers {
		t.Fatalf("got %d servers, want the bound of %d", len(got), maxDNSServers)
	}
}

func writeRoutingFile(t *testing.T, dir, name, content string) string {
	t.Helper()
	path := filepath.Join(dir, name)
	if err := os.WriteFile(path, []byte(content), 0o600); err != nil {
		t.Fatal(err)
	}
	return path
}

func TestReadRoutingReportsGatewayAndResolver(t *testing.T) {
	dir := t.TempDir()
	route := writeRoutingFile(t, dir, "route", procNetRouteBridge)
	resolv := writeRoutingFile(t, dir, "resolv.conf", "nameserver 100.100.100.100\nnameserver fd7a:115c:a1e0::53\nsearch tail.example.test\n")

	got := readRoutingFrom(route, resolv, filepath.Join(dir, "absent"))
	want := &agentshost.NetworkRouting{
		DefaultGateways: []agentshost.NetworkGateway{{Address: "192.168.0.1", Interface: "vmbr0"}},
		DNSServers:      []string{"100.100.100.100", "fd7a:115c:a1e0::53"},
	}
	if !reflect.DeepEqual(got, want) {
		t.Fatalf("routing = %+v, want %+v", got, want)
	}
}

// systemd-resolved puts its loopback stub in resolv.conf. The servers names
// are really sent to are in its second file, and those are what is reported.
func TestReadRoutingLooksPastTheResolvedStub(t *testing.T) {
	dir := t.TempDir()
	resolv := writeRoutingFile(t, dir, "resolv.conf", "nameserver 127.0.0.53\noptions edns0 trust-ad\n")
	upstream := writeRoutingFile(t, dir, "upstream.conf", "nameserver 192.168.0.53\nnameserver 192.168.0.1\n")

	got := readRoutingFrom(filepath.Join(dir, "absent"), resolv, upstream)
	if got == nil || !reflect.DeepEqual(got.DNSServers, []string{"192.168.0.53", "192.168.0.1"}) {
		t.Fatalf("routing = %+v, want the forwarders", got)
	}
	if got.DefaultGateways != nil {
		t.Fatalf("no route table was readable, so no gateway is known: %+v", got.DefaultGateways)
	}
}

// A host that runs its own resolver on loopback has no forwarder file. The
// loopback address is then the truth and stays.
func TestReadRoutingKeepsALocalResolver(t *testing.T) {
	dir := t.TempDir()
	resolv := writeRoutingFile(t, dir, "resolv.conf", "nameserver 127.0.0.1\n")

	got := readRoutingFrom(filepath.Join(dir, "absent"), resolv, filepath.Join(dir, "absent"))
	if got == nil || !reflect.DeepEqual(got.DNSServers, []string{"127.0.0.1"}) {
		t.Fatalf("routing = %+v, want the local resolver", got)
	}

	// An empty forwarder file does not erase it either.
	empty := writeRoutingFile(t, dir, "upstream.conf", "# no servers\n")
	got = readRoutingFrom(filepath.Join(dir, "absent"), resolv, empty)
	if got == nil || !reflect.DeepEqual(got.DNSServers, []string{"127.0.0.1"}) {
		t.Fatalf("routing = %+v, want the local resolver", got)
	}
}

// A platform with neither file sends nothing, which the server reads as
// unknown. An empty object would read as a host with no gateway.
func TestReadRoutingIsNilWhenTheHostStatesNothing(t *testing.T) {
	dir := t.TempDir()
	if got := readRoutingFrom(filepath.Join(dir, "a"), filepath.Join(dir, "b"), filepath.Join(dir, "c")); got != nil {
		t.Fatalf("routing = %+v, want nil", got)
	}
	blank := writeRoutingFile(t, dir, "resolv.conf", "search lan\n")
	if got := readRoutingFrom(filepath.Join(dir, "a"), blank, filepath.Join(dir, "c")); got != nil {
		t.Fatalf("routing = %+v, want nil", got)
	}
}
